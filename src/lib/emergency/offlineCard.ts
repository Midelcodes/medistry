/**
 * MEDISTRY Offline Emergency Card: printable ID-1 card (85.6mm x 54mm) with a real QR code.
 * FRONT: logo, title, QR (${APP_URL}/s#<ES256 token>) and scanning instructions.
 * BACK: the core triage fields as plain text, readable with no phone at all.
 * Opt-in items (conditions, medications, recent diagnosis) are only inside the QR, never printed.
 */

